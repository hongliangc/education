// 把一篇短篇包装成"单章 tale"：text/questions/moral 即原 Story 字段。
function tale(b: {
  id: string;
  emoji: string;
  title: string;
  text: string;
  questions: StoryBook["chapters"][number]["questions"];
  moral: string;
  ageBand?: StoryBook["ageBand"];
}): StoryBook {
  return {
    id: b.id,
    title: b.title,
    emoji: b.emoji,
    kind: "tale",
    ageBand: b.ageBand ?? "5-7",
    chapters: [
      { idx: 0, title: b.title, emoji: b.emoji, text: b.text, questions: b.questions, moral: b.moral },
    ],
  };
}

